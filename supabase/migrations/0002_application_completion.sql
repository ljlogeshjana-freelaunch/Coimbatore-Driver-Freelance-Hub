-- Additive migration: retain existing data and restrict direct browser table access.
create table if not exists public.freelancing_requests (
 id bigint generated by default as identity primary key,
 customer_id uuid references public.users(id) on delete set null,
 service text not null,
 customer_name text not null,
 email text not null,
 details text not null,
 status text not null default 'pending' check (status in ('pending','in_progress','completed','cancelled')),
 created_at timestamptz not null default now()
);
create index if not exists freelance_customer_created on public.freelancing_requests(customer_id, created_at desc);
create index if not exists freelance_created on public.freelancing_requests(created_at desc);

-- Complete RLS coverage for data tables. The API connects directly using its
-- database credential; browser clients receive no policies granting broad access.
alter table public.customers enable row level security;
alter table public.pricing_settings enable row level security;
alter table public.duty_events enable row level security;
alter table public.duty_breaks enable row level security;
alter table public.invoices enable row level security;
alter table public.payments enable row level security;
alter table public.notifications enable row level security;
alter table public.freelancing_requests enable row level security;
alter table public.messages enable row level security;

-- Replace the permissive all-operations profile policy with owner-only access.
drop policy if exists "profile owner read/update" on public.profiles;
create policy "profile owner select" on public.profiles for select using (user_id = auth.uid());
create policy "profile owner insert" on public.profiles for insert with check (user_id = auth.uid());
create policy "profile owner update" on public.profiles for update using (user_id = auth.uid()) with check (user_id = auth.uid());

-- The browser can read its notifications; only trusted backend can create/change them.
create policy "notifications owner read" on public.notifications for select using (user_id = auth.uid());
-- Customers can see their own freelance enquiries, while public submissions and
-- privileged status updates go through the validated API only.
create policy "freelance owner read" on public.freelancing_requests for select using (customer_id = auth.uid());

-- There are intentionally no direct client write policies for roles, assignments,
-- duty events, billing, payments, audit records, login activity, or pricing.
