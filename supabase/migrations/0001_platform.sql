-- Apply in Supabase SQL editor or with the Supabase CLI. API migrations are managed separately from SQLAlchemy metadata.
create extension if not exists pgcrypto;
create table if not exists public.users (
 id uuid primary key references auth.users(id) on delete cascade,
 email text not null unique,
 role text not null default 'customer' check (role in ('customer','driver','admin')),
 created_at timestamptz not null default now()
);
create table if not exists public.profiles (
 user_id uuid primary key references public.users(id) on delete cascade,
 full_name text not null default '', phone text not null default ''
);
create table if not exists public.customers (user_id uuid primary key references public.users(id) on delete cascade);
create table if not exists public.drivers (
 user_id uuid primary key references public.users(id) on delete cascade,
 approved boolean not null default false, commercial boolean not null default false
);
create table if not exists public.pricing_packages (
 id bigint generated by default as identity primary key,
 category text not null check(category in ('commercial','non_commercial')),
 name text not null, duration_minutes integer not null check(duration_minutes>0),
 price numeric(10,2) not null check(price>=0), surcharge numeric(10,2) not null default 50 check(surcharge>=0), enabled boolean not null default true
);
create table if not exists public.pricing_settings (key text primary key, value jsonb not null default '{}'::jsonb);
create table if not exists public.bookings (
 id bigint generated by default as identity primary key,
 customer_id uuid not null references public.users(id), pickup text not null, destination text not null,
 travel_at timestamptz not null, trip_type text not null, category text not null,
 package_id bigint not null references public.pricing_packages(id), requirements text not null default '',
 status text not null default 'pending', created_at timestamptz not null default now()
);
create table if not exists public.driver_assignments (
 id bigint generated by default as identity primary key, booking_id bigint not null references public.bookings(id) on delete cascade,
 driver_id uuid not null references public.drivers(user_id), status text not null default 'assigned', unique(booking_id,driver_id)
);
create table if not exists public.driver_duty_sessions (
 id bigint generated by default as identity primary key, booking_id bigint not null references public.bookings(id),
 driver_id uuid not null references public.drivers(user_id), package_id bigint not null references public.pricing_packages(id),
 started_at timestamptz not null default now(), ended_at timestamptz, paused_at timestamptz, paused_seconds integer not null default 0,
 status text not null default 'active', billable_minutes integer, total_amount numeric(10,2)
);
create unique index if not exists one_open_duty_per_driver on public.driver_duty_sessions(driver_id) where ended_at is null;
create table if not exists public.duty_events (id bigint generated by default as identity primary key, session_id bigint not null references public.driver_duty_sessions(id) on delete cascade, actor_id uuid not null, action text not null, occurred_at timestamptz not null default now());
create table if not exists public.duty_breaks (id bigint generated by default as identity primary key, session_id bigint not null references public.driver_duty_sessions(id) on delete cascade, started_at timestamptz not null, ended_at timestamptz);
create table if not exists public.invoices (id bigint generated by default as identity primary key, booking_id bigint not null references public.bookings(id), total numeric(10,2) not null, created_at timestamptz not null default now());
create table if not exists public.payments (id bigint generated by default as identity primary key, invoice_id bigint not null references public.invoices(id), amount numeric(10,2) not null, status text not null default 'pending', provider_reference text);
create table if not exists public.notifications (id bigint generated by default as identity primary key, user_id uuid references public.users(id), title text not null, body text not null, read_at timestamptz, created_at timestamptz not null default now());
create table if not exists public.login_activity (id bigint generated by default as identity primary key, user_id uuid not null references public.users(id), email text not null, account_type text not null, logged_at timestamptz not null default now());
create table if not exists public.freelancing_requests (id bigint generated by default as identity primary key, customer_id uuid references public.users(id), service text not null, details text not null, status text not null default 'pending', created_at timestamptz not null default now());
create table if not exists public.messages (id bigint generated by default as identity primary key, sender_id uuid not null references public.users(id), recipient_id uuid not null references public.users(id), body text not null, created_at timestamptz not null default now());
create table if not exists public.audit_logs (id bigint generated by default as identity primary key, actor_id uuid not null, action text not null, entity_type text not null, entity_id text not null, created_at timestamptz not null default now());
create index if not exists bookings_customer_created on public.bookings(customer_id, created_at desc);
create index if not exists bookings_status_travel on public.bookings(status, travel_at);
create index if not exists assignments_driver on public.driver_assignments(driver_id);
create index if not exists login_activity_time on public.login_activity(logged_at desc);

