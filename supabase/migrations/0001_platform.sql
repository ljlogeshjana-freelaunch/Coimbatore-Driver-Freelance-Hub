alter table public.drivers enable row level security;
alter table public.bookings enable row level security;
alter table public.driver_assignments enable row level security;
alter table public.driver_duty_sessions enable row level security;
alter table public.pricing_packages enable row level security;
alter table public.login_activity enable row level security;
alter table public.audit_logs enable row level security;
create policy "users read own" on public.users for select using (id = auth.uid());
create policy "profile owner read/update" on public.profiles for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "pricing public read" on public.pricing_packages for select using (enabled);
create policy "customer reads own bookings" on public.bookings for select using (customer_id = auth.uid());
create policy "customer creates own booking" on public.bookings for insert with check (customer_id = auth.uid());
create policy "driver sees assigned bookings" on public.driver_assignments for select using (driver_id = auth.uid());
create policy "driver sees own duty" on public.driver_duty_sessions for select using (driver_id = auth.uid());
create policy "driver sees own profile" on public.drivers for select using (user_id = auth.uid());
